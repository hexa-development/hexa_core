-- users.inventory กับ users.loadout แบ่งกันด้วยตัวนี้ตัวเดียว ถ้าฝั่งเซฟกับฝั่งโหลดตัดสินไม่ตรงกัน อาวุธจะหายหรือถูกนับซ้ำ

-- ห้ามเปลี่ยนไปเช็ค Shared.Items[name].type เพราะแคตตาล็อกสร้างหลังต่อ DB เซฟก่อนโหลดเสร็จจะเสีย ammo/serial ถาวร
function Shared.IsWeapon(name)
    if type(name) ~= 'string' then return false end
    name = name:lower()
    -- แคตตาล็อกด้านบนมาก่อน แล้ว fallback ชื่อขึ้นต้น weapon_ ให้ครอบคลุมอาวุธที่เซิร์ฟเพิ่มเองแต่ยังไม่ได้ใส่แคตตาล็อก
    return Shared.Weapons[name] ~= nil or name:sub(1, 7) == 'weapon_'
end
